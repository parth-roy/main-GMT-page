export const ALL_TRUCKS = TRUCK_CATEGORIES.flatMap((c) =>
  c.trucks.map((t) => ({ ...t, categoryId: c.id, categoryTitle: c.title }))
)

export function findTruckById(truckId) {
  if (!truckId) return ALL_TRUCKS[0]
  return ALL_TRUCKS.find((t) => t.id === truckId) || ALL_TRUCKS[0]
}

export function getDefaultTruckForCategory(categoryId) {
  const cat = TRUCK_CATEGORIES.find((c) => c.id === categoryId) || TRUCK_CATEGORIES[0]
  // Default to a popular mid-size truck
  if (cat.id === "open_truck") {
    return cat.trucks.find((t) => t.id === "open_14ft_4ton") || cat.trucks[0]
  }
  if (cat.id === "container_truck") {
    return cat.trucks.find((t) => t.id === "cont_14ft_3_5ton") || cat.trucks[0]
  }
  return cat.trucks[0]
}
